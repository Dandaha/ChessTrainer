// Builds openingTable.ts from Lichess's opening names (github.com/lichess-org/chess-openings, CC0):
//   npx tsx scripts/build-openings.ts <folder with a.tsv … e.tsv>
// Each line's moves are played to the position they reach, so a game is classified by position and
// a transposition into a named opening is still recognised.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGame } from '../pgn.ts';
import { mainlineFrom } from '../tree.ts';
import { positionKey } from '../positionKey.ts';

const folder = process.argv[2];
if (!folder) throw new Error('Give the folder that holds a.tsv … e.tsv.');
const table = new Map<string, [string, string]>();
for (const volume of ['a', 'b', 'c', 'd', 'e']) {
  const lines = readFileSync(join(folder, `${volume}.tsv`), 'utf8').split('\n').slice(1).filter(Boolean);
  for (const line of lines) {
    const [eco, name, pgn] = line.split('\t') as [string, string, string];
    const end = mainlineFrom(parseGame(`${pgn} *`).root).at(-1)!;
    const key = positionKey(end.fen);
    if (!table.has(key)) table.set(key, [eco, name]);
  }
}
const rows = [...table].map(([key, [eco, name]]) => `  [${JSON.stringify(key)}, ${JSON.stringify(eco)}, ${JSON.stringify(name)}],`);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'openingTable.ts');
writeFileSync(
  out,
  `// Generated by scripts/build-openings.ts from Lichess's opening names (github.com/lichess-org/chess-openings),\n// released under CC0. Do not edit by hand: change the source and run the script again.\n\n/** [position key, ECO code, opening name], one per named position. */\nexport const OPENINGS: readonly (readonly [string, string, string])[] = [\n${rows.join('\n')}\n];\n`,
);
console.log(`${table.size} named positions written to ${out}`);
